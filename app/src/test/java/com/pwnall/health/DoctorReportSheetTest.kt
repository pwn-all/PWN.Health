    // --- right to left -------------------------------------------------------------------------------

    /** The same sheet, mirrored: every line at the other side of the page and anchored by its other end. */
    @Test
    fun aRightToLeftSheetIsTheSameSheetMirrored() {
        val report = sheet(filler(40), labs)
        val ltr = layout(report).flatten()
        val rtl = layout(report, rtl = true).flatten()
        assertEquals(ltr.size, rtl.size)
        ltr.zip(rtl).forEach { (left, right) ->
            when (left) {
                is TextOp -> {
                    right as TextOp
                    assertEquals(left.text, right.text)
                    assertEquals(left.y, right.y, 0f)
                    assertEquals(PAGE_WIDTH - left.x, right.x, 0.001f)
                    assertEquals(!left.rightAligned, right.rightAligned)
                }

                is RuleOp -> assertEquals(left, right)

                is ChartOp -> fail("this sheet has no chart; a chart's mirroring is pinned on its own below")

                is PainDrawingOp -> fail("this sheet has no pain drawing; its mirroring is pinned on its own below")
            }
        }
    }

