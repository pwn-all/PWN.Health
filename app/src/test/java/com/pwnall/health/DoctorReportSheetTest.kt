    // --- line breaking ---------------------------------------------------------------------------

    private fun stringIn(folder: String, name: String): String =
        File("src/main/res/$folder/ui.xml").readText()
            .substringAfter("<string name=\"$name\">").substringBefore("</string>")

    private val closing = "。、，）」".toSet()

    /**
     * Japanese and Chinese are broken between ideographs, not only at spaces: a line is filled to
     * the column before the next starts, and no line starts with closing punctuation.
     */
    @Test
    fun chineseAndJapaneseFillTheirLinesAndKeepTheirPunctuation() {
        val width = 200f
        val measure: (String) -> Float = { it.length * 10f }
        listOf(
            Triple("values-ja", "report_note_not_medical", Locale.JAPANESE),
            Triple("values-ja", "report_note_labs", Locale.JAPANESE),
            Triple("values-zh", "report_note_not_medical", Locale.CHINESE),
            Triple("values-zh", "report_note_labs", Locale.CHINESE),
        ).forEach { (folder, name, locale) ->
            val text = stringIn(folder, name)
            val lines = wrapText(text, width, locale, measure)
            assertEquals(
                "$folder/$name lost text",
                text.filterNot(Char::isWhitespace),
                lines.joinToString("").filterNot(Char::isWhitespace),
            )
            lines.forEach { line ->
                assertTrue("$folder/$name ran past the column: $line", measure(line) <= width)
                assertFalse("$folder/$name starts a line with ${line.first()}", line.first() in closing)
            }
            lines.dropLast(1).forEach { line ->
                assertTrue("$folder/$name left a short line: $line", measure(line) >= width * 0.6f)
            }
        }
    }

    /** A word wider than the column is cut by character, and never inside one. */
    @Test
    fun aWordWiderThanTheColumnIsCutBetweenCharacters() {
        val measure: (String) -> Float = { it.length * 5f }
        val word = "Hydroxychloroquine"
        val pieces = wrapText("take $word daily", 30f, Locale.ENGLISH, measure)
        assertEquals("take${word}daily", pieces.joinToString("").filterNot(Char::isWhitespace))
        assertTrue(pieces.all { measure(it) <= 30f })

        val faces = wrapText("😀😀😀", 15f, Locale.ENGLISH, measure)
        assertEquals(3, faces.size)
        assertTrue(faces.all { it.codePointCount(0, it.length) == 1 })
    }

    /** Ordinary prose wraps at the spaces, greedily. */
    @Test
    fun englishWrapsAtItsSpaces() {
        val measure: (String) -> Float = { it.length * 5f }
        assertEquals(
            listOf("one two", "three"),
            wrapText("one two three", measure("one two"), Locale.ENGLISH, measure),
        )
        assertEquals(emptyList<String>(), wrapText("", 100f, Locale.ENGLISH, measure))
    }

