/**
 * The sheet as it is laid out, and the page that decides what goes on it.
 *
 * The layout runs here without a device: it is handed a measure of five points a character and a
 * resolver that prints every string resource as its own name, so a test can read which line landed
 * on which page, at which x, and anchored at which end.
 */
class DoctorReportSheetTest {
    private val today: LocalDate = LocalDate.of(2026, 9, 23)
    private val from: LocalDate = today.minusMonths(6)
    private val stringNames: Map<Int, String> = R.string::class.java.fields.associate { it.getInt(null) to it.name }

    /** Every resource as its name and its arguments, so a line on the page says which string it is. */
    private fun words(text: ReportText): String = when (text) {
        is ReportText.Plain -> text.text

        is ReportText.Res ->
            (listOf(stringNames.getValue(text.id)) + text.args.map { if (it is ReportText) words(it) else "$it" })
                .joinToString(" ")

        is ReportText.Quantity -> "plural ${text.count}"

        is ReportText.Day -> text.day.toString()

        is ReportText.Join -> text.parts.joinToString(text.separator, transform = ::words)
    }

    private fun layout(
        report: DoctorReport,
        rtl: Boolean = false,
        generated: ReportText = ReportText.Plain("generated"),
    ): List<List<SheetOp>> =
        SheetLayout(::words, { line, _ -> line.length * 5f }, Locale.ENGLISH, rtl)
            .apply { compose(report, generated) }
            .pages

    /**
     * The day in "Generated by … on …" is put into words by the sheet's own resolver, the one that
     * carries the country's date pattern, under the notes and in the page's foot. A finished string
     * resolved elsewhere would carry the international pattern beside rows printed in the country's.
     */
    @Test
    fun theGeneratedLineIsResolvedByTheSheetItself() {
        val generated = ReportText.Res(R.string.report_generated, listOf("PWN.Health", "1.0", ReportText.Day(today)))

        val lines = layout(sheet(), generated = generated).lines()

        assertEquals(2, lines.count { it == "report_generated PWN.Health 1.0 2026-09-23" })
    }

    private fun sheet(vararg sections: ReportSection) = DoctorReport(
        request = ReportRequest(from = from, to = today),
        sections = sections.toList(),
        notes = listOf(ReportText.Plain("A note.")),
        filled = emptySet(),
    )

    private fun List<List<SheetOp>>.pageOf(text: String): Int =
        indexOfFirst { page -> page.any { it is TextOp && it.text == text } }
            .also { assertTrue("\"$text\" is not on any page", it >= 0) }

    private fun List<List<SheetOp>>.lines(): List<String> = flatten().filterIsInstance<TextOp>().map(TextOp::text)

    private fun builtReport(
        parts: Set<ReportPart>,
        allergies: String = "",
        days: List<DaySteps> = emptyList(),
    ): DoctorReport = doctorReport(
        sources = ReportSources(
            profile = UserProfile(
                sex = "FEMALE",
                weightKg = 64.0,
                heightCm = 168,
                birthDate = "1990-02-14",
                allergies = allergies,
            ),
            entries = emptyList(),
            days = days,
        ),
        request = ReportRequest(from = from, to = today, parts = parts),
        today = today,
        zone = ZoneOffset.UTC,
    )

    // --- an empty section keeps its caveat ------------------------------------------------------------

    /**
     * "None known" covers the food-label allergens and nothing else. Printed without the caveat that
     * says so, it reads to a prescriber as no known allergies at all, medicines included.
     */
    @Test
    fun noneKnownIsPrintedWithTheLineThatLimitsIt() {
        val report = builtReport(parts = emptySet(), allergies = AllergyAnswer.NoneKnown.stored())
        val allergies = report.sections.single { it.part == ReportPart.ALLERGIES }
        assertTrue(allergies.rows.isEmpty())
        assertEquals(SectionPresence.NO_KNOWN, allergies.presence)
        assertTrue(ReportText.Res(R.string.report_caveat_allergies) in sectionNotes(allergies))

        val lines = layout(report).lines()
        val said = lines.indexOf("section_no_known")
        assertTrue("the empty label is missing", said >= 0)
        assertEquals("report_caveat_allergies", lines[said + 1])
    }

    /** "Never tested" and "never asked" share an empty label; only the caveat tells them apart. */
    @Test
    fun neverTestedIsToldApartFromNeverAsked() {
        val untested = layout(builtReport(parts = emptySet(), allergies = AllergyAnswer.NotTested.stored())).lines()
        val unasked = layout(builtReport(parts = emptySet())).lines()

        assertTrue("report_caveat_allergies_untested" in untested)
        assertFalse("report_caveat_allergies_untested" in unasked)
        assertNotEquals(untested, unasked)
    }

    // --- what stays together ----------------------------------------------------------------------

    private fun filler(rows: Int) = ReportSection(
        part = ReportPart.ACTIVITY,
        rows = (1..rows).map { ReportRow(ReportText.Plain("filler $it"), ReportText.Plain("1")) },
    )

    /** A section whose first row wraps to two lines in its note column and ends in a caveat. */
    private val labs = ReportSection(
        part = ReportPart.LABS,
        rows = listOf(
            ReportRow(
                label = ReportText.Plain("first marker"),
                value = ReportText.Plain("5.1"),
                note = ReportText.Plain("12 Feb 2026 after a meal well above the band"),
            ),
            ReportRow(ReportText.Plain("last marker"), ReportText.Plain("4.2")),
        ),
        completeness = Completeness(daysWithData = 2, expectedDays = 183, measurements = 2),
        provenance = listOf(Provenance(ProvenanceCategory.MANUAL)),
        caveatRes = R.string.report_caveat_band,
    )

    /**
     * Wherever the heading falls, its first row — two lines of it — is on the same page, and the
     * section's last row is on the page of the notes that qualify it. The filler walks the heading
     * down the page one row at a time, past every point a page can break at.
     */
    @Test
    fun aHeadingKeepsItsFirstRowAndTheLastRowKeepsItsNotes() {
        (0..70).forEach { filler ->
            val pages = layout(sheet(filler(filler), labs))
            val heading = pages.pageOf("labs_title")
            assertEquals("heading left alone after $filler rows", heading, pages.pageOf("first marker"))
            val last = pages.pageOf("last marker")
            assertEquals("completeness left after $filler rows", last, pages.pageOf("report_completeness 2 183 2"))
            val provenance = pages.pageOf("report_provenance provenance_manual")
            assertEquals("provenance left after $filler rows", last, provenance)
            assertEquals("caveat left after $filler rows", last, pages.pageOf("report_caveat_band"))
        }
    }

    // --- charts -------------------------------------------------------------------------------------

    private fun chart(width: ChartWidth = ChartWidth.FULL, points: Int = 6) = ReportChart(
        series = listOf(
            ChartSeries(
                (0 until points).map { ChartPoint(today.minusDays(it * 20L), 7_000.0 + it * 300) },
                ChartStyle.LINE_DOTS,
            ),
        ),
        unit = ReportText.Plain("steps a day"),
        from = from,
        to = today,
        width = width,
    )

    private fun charted(vararg charts: ReportChart) = labs.copy(charts = charts.toList())

    private fun List<List<SheetOp>>.charts(): List<Pair<Int, ChartOp>> =
        flatMapIndexed { index, page -> page.filterIsInstance<ChartOp>().map { index to it } }

    /** Heading, then the charts, a gap, then the rows: a doctor reads the trend before the figures. */
    @Test
    fun chartsComeUnderTheHeadingAndAboveTheRows() {
        val page = layout(sheet(charted(chart(), chart(ChartWidth.HALF)))).first()
        val heading = page.indexOfFirst { it is TextOp && it.text == "labs_title" }
        val row = page.indexOfFirst { it is TextOp && it.text == "first marker" }
        val charts = page.withIndex().filter { it.value is ChartOp }
        assertEquals(2, charts.size)
        assertTrue(charts.all { it.index in heading until row })
        val headingY = (page[heading] as TextOp).y
        // A row's first line is set 10 pt under its top; the rest is the gap under the charts.
        val rowTop = (page[row] as TextOp).y - 10f
        charts.map { it.value as ChartOp }.forEach { chart ->
            assertTrue(chart.box.top > headingY)
            assertTrue("no room between the charts and the rows", rowTop - chart.box.bottom >= 8f)
        }
    }

    /**
     * Wherever the section falls, no chart is cut by the foot of a page, the heading keeps the
     * first chart, and somewhere along the walk the page breaks between the two charts rather than
     * through one.
     */
    @Test
    fun aChartMovesWholeToTheNextPageAndTheHeadingKeepsTheFirst() {
        var split = false
        (0..70).forEach { filler ->
            val pages = layout(sheet(filler(filler), charted(chart(), chart())))
            val charts = pages.charts()
            assertEquals(2, charts.size)
            assertEquals("heading left alone after $filler rows", pages.pageOf("labs_title"), charts.first().first)
            charts.forEach { (_, chart) ->
                assertTrue("cut after $filler rows", chart.box.top >= MARGIN && chart.box.bottom <= CONTENT_BOTTOM)
            }
            assertTrue(pages.pageOf("first marker") >= charts.last().first)
            if (charts.first().first != charts.last().first) {
                split = true
                assertEquals(MARGIN, charts.last().second.box.top, 0f)
            }
        }
        assertTrue("the walk never broke a page between the charts", split)
    }

    /** Two half-width charts side by side, an odd one alone at the start, a full-width one across. */
    @Test
    fun twoHalfChartsShareARow() {
        val half = chart(ChartWidth.HALF)
        val charts = layout(sheet(charted(half, half, half, chart()))).charts().map { it.second }
        assertEquals(4, charts.size)
        val (first, second, third) = charts
        val full = charts.last()
        assertEquals(first.box.top, second.box.top, 0f)
        assertEquals(first.box.width, second.box.width, 0f)
        assertEquals(MARGIN, first.box.left, 0f)
        assertEquals(RIGHT_EDGE, second.box.right, 1e-3f)
        assertTrue(first.box.right < second.box.left)
        assertEquals(MARGIN, third.box.left, 0f)
        assertEquals(first.box.width, third.box.width, 0f)
        assertTrue(third.box.top > first.box.bottom)
        assertEquals(RIGHT_EDGE - MARGIN, full.box.width, 1e-3f)
        assertTrue(full.box.top > third.box.bottom)

        // Right to left, the first of a pair is the one on the right, where the reader starts.
        val mirrored = layout(sheet(charted(half, half)), rtl = true).charts().map { it.second }
        assertEquals(RIGHT_EDGE, mirrored.first().box.right, 1e-3f)
        assertEquals(MARGIN, mirrored.last().box.left, 1e-3f)
    }

    /** A chart with nothing to draw leaves no hole: the next half-width chart takes its place. */
    @Test
    fun anEmptyChartLeavesNoHole() {
        val charts = layout(sheet(charted(chart(ChartWidth.HALF, points = 0), chart(ChartWidth.HALF)))).charts()
        assertEquals(MARGIN, charts.single().second.box.left, 0f)
    }

    /** A section that says it has nothing draws nothing either. */
    @Test
    fun aSectionWithNoRowsDrawsNoChart() {
        val empty = ReportSection(
            part = ReportPart.ACTIVITY,
            rows = emptyList(),
            presence = SectionPresence.NO_DATA,
            charts = listOf(chart()),
