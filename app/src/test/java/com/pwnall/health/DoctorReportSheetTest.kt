    }

    // --- the pain drawing ------------------------------------------------------------------------------

    private val kneeStroke = PainStroke(PainView.FRONT, 0.035f, listOf(Offset(0.64f, 0.615f), Offset(0.70f, 0.62f)))
    private val backDab = PainStroke(PainView.BACK, 0.012f, listOf(Offset(0.62f, 0.29f)))

    private fun pain(drawing: PainSheetDrawing?, vararg charts: ReportChart) = ReportSection(
        part = ReportPart.PAIN,
        rows = listOf(ReportRow(ReportText.Plain("any pain"), ReportText.Plain("7 of 10"))),
        caveatRes = R.string.report_caveat_pain,
        charts = charts.toList(),
        painDrawing = drawing,
    )

    private fun List<List<SheetOp>>.drawings(): List<Pair<Int, PainDrawingOp>> =
        flatMapIndexed { index, page -> page.filterIsInstance<PainDrawingOp>().map { index to it } }

    /**
     * The drawing comes under the charts and above the rows: the front at the margin and the back
     * beside it, each plate in the plates' own proportions, and every stroke put into its plate's box
     * where it was painted, its brush scaled with the plate — one list of marks per entry, an entry
     * with nothing on a view left off that view. The caption counts the entries drawn.
     */
    @Test
    fun theDrawingPutsEveryStrokeWhereItWasPaintedInItsBox() {
        val drawing = PainSheetDrawing("FEMALE", listOf(listOf(kneeStroke), listOf(kneeStroke, backDab)))
        val half = chart(ChartWidth.HALF)
        val page = layout(sheet(pain(drawing, half, half))).first()
        val op = page.filterIsInstance<PainDrawingOp>().single()
        assertEquals("FEMALE", op.sex)
        val (front, back) = op.plates
        assertEquals(PainView.FRONT, front.view)
        assertEquals(PainView.BACK, back.view)
        assertEquals(MARGIN, front.box.left, 0f)
        assertEquals(PAIN_PLATE_HEIGHT, front.box.bottom - front.box.top, 1e-3f)
        assertEquals(PAIN_PLATE_HEIGHT * PLATE_ASPECT, front.box.width, 1e-3f)
        assertEquals(front.box.right + PAIN_PLATE_GUTTER, back.box.left, 1e-3f)
        assertEquals(front.box.top, back.box.top, 0f)

        assertEquals(2, front.entries.size)
        val knee = front.entries.first().single()
        assertEquals(front.box.left + 0.64f * front.box.width, knee.points.first().x, 1e-3f)
        assertEquals(front.box.top + 0.615f * PAIN_PLATE_HEIGHT, knee.points.first().y, 1e-3f)
        assertEquals(front.box.left + 0.70f * front.box.width, knee.points.last().x, 1e-3f)
        assertEquals(0.035f * PAIN_PLATE_HEIGHT, knee.radius, 1e-3f)
        val dab = back.entries.single().single()
        assertEquals(
            ChartDot(back.box.left + 0.62f * back.box.width, back.box.top + 0.29f * PAIN_PLATE_HEIGHT),
            dab.points.single(),
        )

        // Charts first, then the drawing, then the rows.
        val charts = page.filterIsInstance<ChartOp>()
        assertEquals(2, charts.size)
        assertTrue(charts.all { it.box.bottom < front.box.top })
        val caption = page.filterIsInstance<TextOp>().single { it.text == "plural 2" }
        assertTrue(caption.y > front.box.bottom)
        val row = page.filterIsInstance<TextOp>().single { it.text == "any pain" }
        assertTrue(row.y > caption.y)
        assertTrue(page.any { it is TextOp && it.text == "pain_view_front" && it.y > front.box.bottom })
    }

