    // --- a row taller than a page ----------------------------------------------------------------

    /**
     * A row moves whole to the next page, and one taller than any page cannot: it is set a line at a
     * time instead. Printed whole, it would run past the foot of the page it was moved to — an
     * attachment described in a few thousand characters would run over the page number and off the
     * paper.
     */
    @Test
    fun aRowTallerThanAPageRunsOnAndLosesNothing() {
        val described = (1..800).joinToString(" ") { "w$it" }
        val row = ReportRow(ReportText.Plain("Attachments"), ReportText.Plain(described), ReportText.Plain("a note"))

        val pages = layout(sheet(ReportSection(ReportPart.VISITS, listOf(row))))
        val text = pages.flatten().filterIsInstance<TextOp>().filter { it.type != SheetType.FOOTER }
        val printed = text.map(TextOp::text).filter { line -> line.split(' ').all { it.matches(Regex("w\\d+")) } }

        assertTrue("the row should not fit one page", pages.size > 2)
        assertTrue("a line was set below the page's foot", text.all { it.y <= CONTENT_BOTTOM })
        assertEquals(described, printed.joinToString(" "))
        assertEquals(1, text.count { it.text == "Attachments" })
        assertEquals(1, text.count { it.text == "a note" })
    }
